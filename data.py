def get_anime_by_id(anime_id):
    return next((a for a in ANIME_LIST if a["id"] == anime_id), None)


def get_average_rating(anime):
    reviews = anime.get("reviews", [])
    if not reviews:
        return 0.0
    return sum(r["rating"] for r in reviews) / len(reviews)
